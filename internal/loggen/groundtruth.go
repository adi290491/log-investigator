package loggen

import (
	"bytes"
	"fmt"
	"time"

	"log-investigator/internal/logstore"
)

// stats describes how often one message occurred in [from, WindowEnd).
type stats struct {
	first   time.Time
	count   int
	ofTotal int // denominator for the rate, e.g. all charges
}

func (s stats) rate() string {
	if s.ofTotal == 0 {
		return "n/a"
	}
	return fmt.Sprintf("%d%%", (s.count*100+s.ofTotal/2)/s.ofTotal)
}

func count(es []logstore.Entry, from time.Time, match, total func(logstore.Entry) bool) stats {
	var s stats
	for _, e := range es {
		if e.Time.Before(from) {
			continue
		}
		if total(e) {
			s.ofTotal++
		}
		if match(e) {
			if s.count == 0 {
				s.first = e.Time
			}
			s.count++
		}
	}
	return s
}

func msgIs(m string) func(logstore.Entry) bool {
	return func(e logstore.Entry) bool { return e.Msg == m }
}

func clock(t time.Time) string { return t.UTC().Format("15:04:05.000") }

// groundTruth renders data/GROUND_TRUTH.md, the eval answer key.
func groundTruth(ds Dataset) []byte {
	isCharge := func(e logstore.Entry) bool { return e.Msg == "charge succeeded" || e.Msg == MsgPoolExhausted }
	isRequest := func(e logstore.Entry) bool { return e.Route != "" && e.Msg != MsgRateLimited && e.Status != 400 }
	isOrder := msgIs("order created")

	pay := count(ds.Payments, PaymentErrorsFrom, msgIs(MsgPoolExhausted), isCharge)
	warn := count(ds.Payments, PoolWarnFrom, msgIs(MsgPoolNearCapacity), func(logstore.Entry) bool { return false })
	ord := count(ds.Orders, OrderErrorsFrom, msgIs(MsgPaymentTimeout), isOrder)
	gw := count(ds.Gateway, GatewayErrorsFrom, msgIs(MsgUpstreamTimeout), isRequest)
	rl := count(ds.Gateway, RateLimitFrom, msgIs(MsgRateLimited), func(logstore.Entry) bool { return false })

	var lastOldPool, firstNewPool logstore.Entry
	for _, e := range ds.Payments {
		if e.Msg != "pool stats" {
			continue
		}
		if e.PoolSize == oldPoolSize {
			lastOldPool = e
		} else if firstNewPool.Msg == "" {
			firstNewPool = e
		}
	}

	var b bytes.Buffer
	p := func(format string, a ...any) { fmt.Fprintf(&b, format+"\n", a...) }

	p("# Ground truth: payments DB pool exhaustion (2026-10-21)")
	p("")
	p("Generated by `cmd/loggen` (seed %d). Do not edit by hand; counts below are computed from the data.", Seed)
	p("Window: %s to %s UTC (end exclusive). The incident is still ongoing at the end of the window.",
		WindowStart.Format(time.RFC3339), WindowEnd.Format(time.RFC3339))
	p("")
	p("## Root cause")
	p("")
	p("The payments deploy `v2.14.0` at %s (change: \"reduced DB pool size 50 -> 5\") shrank the payments",
		PaymentsDeployAt.Format(time.RFC3339))
	p("DB connection pool from 50 to 5. Normal load uses 5-15 connections, so the pool saturates and charges")
	p("fail waiting for a connection. The failure cascades up the chain gateway -> orders -> payments -> DB:")
	p("orders times out calling payments, and gateway returns 502/503 to clients.")
	p("")
	p("Remediation: roll back payments to the previous version or restore the pool size to 50.")
	p("")
	p("## Timeline (UTC)")
	p("")
	p("| Time | Service | Event |")
	p("|---|---|---|")
	p("| 13:15:00 | orders | Deploy `v3.8.1` \"bump logging library\". Harmless: no change in orders errors or latency afterwards. |")
	p("| 13:40-13:47 | gateway | Red herring: %d `warn` \"%s\" (status 429). No errors, no downstream effect. |", rl.count, MsgRateLimited)
	p("| 14:02:00 | payments | Deploy `v2.14.0` \"reduced DB pool size 50 -> 5\". **Root cause.** |")
	p("| %s | payments | First `pool stats` line with `pool_size` 5 (last with 50 at %s). |", clock(firstNewPool.Time), clock(lastOldPool.Time))
	p("| %s | payments | First `warn` \"%s\" (`pool_in_use` 5, `pool_size` 5); charge latency climbing. |", clock(warn.first), MsgPoolNearCapacity)
	p("| %s | payments | First `error` \"%s\". |", clock(pay.first), MsgPoolExhausted)
	p("| %s | orders | First `error` \"%s\". |", clock(ord.first), MsgPaymentTimeout)
	p("| %s | gateway | First `error` \"%s\" (502/503). |", clock(gw.first), MsgUpstreamTimeout)
	p("")
	p("## Impact from first error to 14:20")
	p("")
	p("| Service | Error | Count | Rate |")
	p("|---|---|---|---|")
	p("| payments | %s | %d | %s of %d charges |", MsgPoolExhausted, pay.count, pay.rate(), pay.ofTotal)
	p("| orders | %s | %d | %s of %d orders |", MsgPaymentTimeout, ord.count, ord.rate(), ord.ofTotal)
	p("| gateway | %s | %d | %s of %d requests |", MsgUpstreamTimeout, gw.count, gw.rate(), gw.ofTotal)
	p("")
	p("## Evidence an ideal investigation cites")
	p("")
	p("1. `error_summary` around 13:55-14:15: errors start in payments at 14:04, then orders (14:04), then gateway (14:05).")
	p("   The earliest and most upstream-of-the-DB failure is payments.")
	p("2. Top payments error is \"%s\"; payments `pool stats` show `pool_size` 5 from 14:02 (was 50).", MsgPoolExhausted)
	p("3. `get_deploys`: payments `v2.14.0` at 14:02:00, \"reduced DB pool size 50 -> 5\", two minutes before the first error.")
	p("4. Shared `trace_id`s link a gateway 502/503 to an orders timeout to a payments pool-exhausted error.")
	p("5. Ruled out: the orders `v3.8.1` deploy at 13:15 (no errors for ~50 minutes after it), and the gateway")
	p("   rate-limit warnings at 13:40-13:47 (warnings only, no errors, stopped well before the incident).")
	p("")
	p("## Background noise (not incident related)")
	p("")
	p("At most one unrelated error per service per 15 minutes: gateway \"request validation failed\" (400),")
	p("orders \"failed to publish order event, will retry\", payments \"fraud check returned malformed response\".")
	return b.Bytes()
}
