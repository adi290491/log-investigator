#!/usr/bin/env bash
# Builds what is needed, runs cmd/bench against the Go and Python servers, and
# writes compare/RESULTS.md. Run from log-investigator/ (make bench does this).
# The Go server is measured only if cmd/server exists.
set -euo pipefail

out=compare/RESULTS.md
py=compare/python/.venv/bin/python
venv=compare/python/.venv
[ -x "$py" ] || compare/python/setup.sh

tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
go build -o "$tmp/bench" ./cmd/bench

servers=()
have_go=0
if [ -d cmd/server ]; then
  have_go=1
  go build -o "$tmp/server" ./cmd/server
  go build -ldflags="-s -w" -o "$tmp/server-stripped" ./cmd/server
  servers+=(-server "go=$tmp/server")
fi
servers+=(-server "python=$py compare/python/server.py")

size_mb() { echo "scale=1; $(stat -f%z "$1" 2>/dev/null || stat -c%s "$1") / 1048576" | bc; }

py_real=$(readlink -f "$py" 2>/dev/null || python3 -c 'import os,sys; print(os.path.realpath(sys.argv[1]))' "$py")
case "$py_real" in
  "$PWD/$venv"/*) py_note="includes the interpreter" ;;
  *) py_note="excludes the interpreter: the venv symlinks to a system-provided Python" ;;
esac

{
  echo "# MCP server comparison: Go vs Python"
  echo
  echo "Generated by \`make bench\` on $(date -u +%Y-%m-%dT%H:%M:%SZ)."
  echo
  echo "## Environment"
  echo
  echo "- Machine: $(sysctl -n machdep.cpu.brand_string 2>/dev/null || uname -m), $(( $(sysctl -n hw.memsize 2>/dev/null || echo 0) / 1073741824 )) GB RAM"
  echo "- OS: $(sw_vers -productName 2>/dev/null || uname -s) $(sw_vers -productVersion 2>/dev/null || uname -r) ($(uname -m))"
  echo "- Go: $(go version | awk '{print $3}'), go-sdk $(go list -m -f '{{.Version}}' github.com/modelcontextprotocol/go-sdk)"
  echo "- Python: $($py -V | awk '{print $2}'), mcp $($py -c 'import importlib.metadata as m; print(m.version("mcp"))')"
  echo
  echo "## Runtime"
  echo
  "$tmp/bench" "${servers[@]}"
  if [ "$have_go" = 0 ]; then
    echo
    echo "Go: pending. cmd/server does not exist yet; rerun \`make bench\` once it does."
  fi
  echo
  echo "## Size on disk"
  echo
  echo "| Artifact | Size (MB) |"
  echo "|---|---|"
  if [ "$have_go" = 1 ]; then
    echo "| Go binary | $(size_mb "$tmp/server") |"
    echo "| Go binary, \`-ldflags=\"-s -w\"\` | $(size_mb "$tmp/server-stripped") |"
  else
    echo "| Go binary | pending |"
    echo "| Go binary, \`-ldflags=\"-s -w\"\` | pending |"
  fi
  echo "| Python venv (\`du -sk $venv\`; $py_note) | $(echo "scale=1; $(du -sk "$venv" | cut -f1) / 1024" | bc) |"
  echo
  echo "## Methodology"
  echo
  echo "- Harness: \`cmd/bench\`, a Go program using the go-sdk client over stdio. It starts the server process itself and connects with \`mcp.IOTransport\` on the process's stdin/stdout."
  echo "- Cold start: wall time from process spawn until the \`tools/list\` response is received (includes \`initialize\`)."
  echo "- Workload: wall time from process spawn through \`initialize\`, \`tools/list\` and 20 sequential \`error_summary\` calls over 13:00-14:20 UTC."
  echo "- Calls only: the 20 \`error_summary\` calls alone, from the same runs."
  echo "- Peak RSS: maximum of \`ps -o rss= -p <pid>\` sampled every 20 ms from spawn until exit. Processes that run for less than a few sampling intervals may have their peak under-reported."
  echo "- Each server is run 10 times; the first run is discarded as warm-up. Reported as median (min-max) of the remaining 9."
  echo "- Both servers load the same \`data/*.jsonl\` (about 4,500 lines) into memory at startup. The Python server re-implements \`internal/logstore\` and returns identical counts."
  echo "- Python uses $venv/bin/python directly (no \`uv run\` wrapper), so the measured process is the interpreter."
  echo "- Lines of code: \`compare/loc.sh PATH...\` counts non-blank, non-comment lines. Python docstrings are counted because the SDK uses them as tool descriptions."
} > "$out"
echo "wrote $out"
